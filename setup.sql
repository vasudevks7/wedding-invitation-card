-- Run this entire script once in the NEW Supabase project's SQL Editor.
-- Creates the RSVP table and locks reads/deletes to the designated admin account.

create table if not exists public.wedding_rsvps (
  id bigint generated by default as identity primary key,
  guest_name text not null check (char_length(trim(guest_name)) between 1 and 120),
  attending boolean not null,
  message text,
  rating smallint check (rating between 1 and 5),
  created_at timestamptz not null default now()
);

alter table public.wedding_rsvps enable row level security;

-- Remove known permissive legacy policies if this SQL is re-run.
drop policy if exists "Allow public insert" on public.wedding_rsvps;
drop policy if exists "Allow public select" on public.wedding_rsvps;
drop policy if exists "Allow public delete" on public.wedding_rsvps;
drop policy if exists "Guests can submit RSVPs" on public.wedding_rsvps;
drop policy if exists "Admin can view RSVPs" on public.wedding_rsvps;
drop policy if exists "Admin can delete RSVPs" on public.wedding_rsvps;

create policy "Guests can submit RSVPs"
on public.wedding_rsvps
for insert
to anon, authenticated
with check (true);

create policy "Admin can view RSVPs"
on public.wedding_rsvps
for select
to authenticated
using ((auth.jwt() ->> 'email') = 'fahadnrfahad@gmail.com');

create policy "Admin can delete RSVPs"
on public.wedding_rsvps
for delete
to authenticated
using ((auth.jwt() ->> 'email') = 'fahadnrfahad@gmail.com');

grant insert on public.wedding_rsvps to anon, authenticated;
grant select, delete on public.wedding_rsvps to authenticated;
grant usage, select on sequence public.wedding_rsvps_id_seq to anon, authenticated;
